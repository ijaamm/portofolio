/**
 * Build Script - Modular to Standalone HTML
 *
 * Script ini membaca index.template.html (atau index.html) dan menggabungkan
 * semua partials (partials/*.html) ke dalam index.html tunggal yang siap saji.
 *
 * Keuntungan:
 * 1. Bisa dibuka langsung secara offline (klik 2x file:///index.html) tanpa CORS error.
 * 2. Siap langsung di-deploy ke GitHub Pages, Vercel, Netlify.
 * 3. Anda tetap bisa mengedit file partials/ secara modular dan menjalankan:
 *    node build.js
 */

const fs = require("fs");
const path = require("path");

const rootDir = __dirname;
const templatePath = fs.existsSync(path.join(rootDir, "index.template.html"))
  ? path.join(rootDir, "index.template.html")
  : path.join(rootDir, "index.html");

const outputPath = path.join(rootDir, "index.html");

let content = fs.readFileSync(templatePath, "utf8");

const templateRegex = /<template\s+data-partial=["']([^"']+)["']\s*><\/template>/gi;

let count = 0;
content = content.replace(templateRegex, (match, partialPath) => {
  const fullPath = path.join(rootDir, partialPath);
  if (fs.existsSync(fullPath)) {
    const partialContent = fs.readFileSync(fullPath, "utf8");
    count += 1;
    console.log(`✓ Menyisipkan: ${partialPath}`);
    return partialContent;
  } else {
    console.warn(`⚠ File partial tidak ditemukan: ${partialPath}`);
    return match;
  }
});

// Update script tag to use script.js directly instead of partials.js
content = content.replace(
  /<script\s+type=["']module["']\s+src=["']js\/partials\.js["']\s*><\/script>/i,
  '<script src="js/script.js" defer></script>'
);

content = `<!-- Generated by node build.js from index.template.html and partials/*.html. Edit those source files. -->\n${content}`;

fs.writeFileSync(outputPath, content, "utf8");
console.log(`\n Berhasil menggabungkan ${count} partial ke dalam index.html!`);
console.log("Sekarang index.html siap dijalankan di browser manapun tanpa web server.");
